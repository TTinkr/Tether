import AppKit
import ApplicationServices
import Darwin


// PasteboardItemSnapshot — one clipboard item: each of its types with that type's bytes


struct PasteboardItemSnapshot {
    var values: [(NSPasteboard.PasteboardType, Data)]
}


// PasteboardSnapshot — the whole clipboard, copied out so it can be put back after a paste


struct PasteboardSnapshot {
    var items: [PasteboardItemSnapshot]

    /*
    Returns nil if the data for any type cannot be read, so a partial copy is never
    mistaken for the whole clipboard. An empty clipboard gives an empty snapshot.
    */
    static func capture() -> PasteboardSnapshot? {
        var items: [PasteboardItemSnapshot] = []
        for source in NSPasteboard.general.pasteboardItems ?? [] {
            var values: [(NSPasteboard.PasteboardType, Data)] = []
            for type in source.types {
                guard let data = source.data(forType: type) else { return nil }
                values.append((type, data))
            }
            items.append(PasteboardItemSnapshot(values: values))
        }
        return PasteboardSnapshot(items: items)
    }

    /*
    Clears the clipboard and writes the saved items back. For an empty snapshot, success
    means the clipboard is empty again. Returns false if the write did not take. Every saved
    type is set on its item first; if any one fails, the clipboard is left untouched rather than
    replaced by a partial copy (setData results used to be ignored).
    */
    func restore(to pasteboard: NSPasteboard = .general) -> Bool {
        var restored: [NSPasteboardItem] = []
        for snapshot in items {
            let item = NSPasteboardItem()
            for (type, data) in snapshot.values {
                guard item.setData(data, forType: type) else { return false }
            }
            restored.append(item)
        }
        pasteboard.clearContents()
        guard !restored.isEmpty else { return pasteboard.pasteboardItems?.isEmpty != false }
        return pasteboard.writeObjects(restored)
    }
}


// DeliveryClipboard — the clipboard item Tokens writes to paste, marked so clipboard history skips it


/*
Tokens borrows the clipboard to paste: every piece of a reveal, a single paste and the early
stop marker. Clipboard-history apps (Raycast, Maccy, Paste, Alfred) recorded each of those
writes, so their history filled with word fragments and talk text the person never copied.
The two nspasteboard.org markers ask those apps to skip a write. The plain-text type is
unchanged, so the destination pastes exactly the same words. The person's own clipboard put
back afterwards (PasteboardSnapshot.restore) and every Copy they ask for are never marked (build 81).
*/
enum DeliveryClipboard {
    static let transientType     = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// One item holding `text` plus both markers (empty data, as the convention asks); nil if any part did not take.
    static func item(_ text: String) -> NSPasteboardItem? {
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string),
              item.setData(Data(), forType: transientType),
              item.setData(Data(), forType: autoGeneratedType) else { return nil }
        return item
    }

    /// Writes `text` to a pasteboard the caller has just cleared. False when the write did not take.
    static func write(_ text: String, to pasteboard: NSPasteboard) -> Bool {
        guard let item = item(text) else { return false }
        return pasteboard.writeObjects([item])
    }
}

