

import Foundation

/// One model's result in Tinkr's own benchmark run.
public struct MeasuredSpeechStats: Sendable, Hashable {
    /// Word error rate in percent over every clip in the run (lower is better).
    public let wer: Double
    /// Median seconds the loaded model takes to turn a finished 10-second talk (8–12 s clips) into text.
    public let talkSeconds: Double
    /// Median seconds from starting the model cold to the text of one 10-second clip.
    public let loadSeconds: Double?
    /// Clips scored.
    public let clips: Int

    public init(wer: Double, talkSeconds: Double, loadSeconds: Double?, clips: Int) {
        self.wer = wer
        self.talkSeconds = talkSeconds
        self.loadSeconds = loadSeconds
        self.clips = clips
    }

    /// The friendlier side of the error rate: words right, in percent.
    public var wordsRight: Double { max(0, 100 - wer) }
}

/// How the run was made, said once under the table.
public struct SpeechBenchmarkRun: Sendable, Hashable {
    /// "MacBook Pro (M5, 24 GB)".
    public let machine: String
    /// The run's start date in America/Los_Angeles, "2026-10-16".
    public let date: String
    /// "LibriSpeech test-clean and test-other, 200 recordings".
    public let clipSet: String
    /// The app build whose speech workers ran ("81").
    public let build: String
    /// The benchmark run id, summary.json's `run_id` ("20261017T010320Z"). Empty only in fixtures.
    public let runID: String

    public init(machine: String, date: String, clipSet: String, build: String, runID: String = "") {
        self.machine = machine
        self.date = date
        self.clipSet = clipSet
        self.build = build
        self.runID = runID
    }
}

