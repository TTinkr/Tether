import Foundation

/// Which writer generation produced a saved π envelope.
public enum PiLayout: String, Sendable, Codable {
    /// "# π\n" + body + "\n\n---\n\n# Metadata\n\n" + "> " lines (TokensDecoration.parts).
    case current
    /// "# π <title>\n\n> *stats*\n…\n\n<body>" (TokensPrompt.format / ThinkingPrompt.format).
    case legacyHeaderFirst
    /// "# π <title>\n\n# Metadata\n\n> …\n\n## Transcript\n\n<body>" (2026-10-10 and older).
    case legacyTranscriptHeading
}

/// The receipt line exactly as stated by the writer; the verifier recomputes it.
public struct PiStats: Equatable, Sendable, Codable {
    public var seconds: Double
    public var words: Int
    public var wpm: Int
    public var pauseCount: Int?
    public var pauseTotal: Double?
    /// Optional " · π-id a1b2c3d4" suffix, once an owner wires PiEnvelopeID into the writers.
    public var piID: String?

    public init(seconds: Double, words: Int, wpm: Int, pauseCount: Int? = nil, pauseTotal: Double? = nil, piID: String? = nil) {
        self.seconds = seconds; self.words = words; self.wpm = wpm
        self.pauseCount = pauseCount; self.pauseTotal = pauseTotal; self.piID = piID
    }
}

/// One placed pause marker. `wordIndex` is the index of the first word after it in spokenText.
public struct PiPause: Equatable, Sendable, Codable {
    public var seconds: Double
    public var wordIndex: Int

    public init(seconds: Double, wordIndex: Int) {
        self.seconds = seconds; self.wordIndex = wordIndex
    }
}

/// A saved talk read back into the fields its writer put in.
public struct PiEnvelope: Equatable, Sendable, Codable {
    public var layout: PiLayout
    public var title: String?
    /// Exact bytes between the layout's delimiters, markers intact.
    public var body: String
    /// Body with pause markers removed and whitespace collapsed; tags such as <num> stay.
    public var spokenText: String
    public var pauses: [PiPause]
    public var stats: PiStats?
    /// Every metadata "> " line after the stats line, verbatim.
    public var notes: [String]
    public var typed: String?
    /// Historical pauses the writer could not place at a word: count and total seconds.
    public var unplacedPauseCount: Int = 0
    public var unplacedPauseTotal: Double = 0
    /// A model-written section the Dev channel appends after the metadata block
    /// ("---" then "## Tinkering"). Not the speaker's words, so never part of body or notes.
    public var generated: String? = nil

    /*
    Order matters: the oldest layout also starts "# π <title>", so it is tried before the
    header-first form. Anything that fits none of the three returns nil; a lone marker is not
    an envelope.
    */
    public static func parse(_ text: String) -> PiEnvelope? {
        if text.hasPrefix("# π\n") { return parseCurrent(text) }
        guard text.hasPrefix("# π ") else { return nil }
        return parseTranscriptHeading(text) ?? parseHeaderFirst(text)
    }

    /// Spoken words and placed pauses of any body, envelope or not.
    public static func spokenText(of body: String) -> String { PiMarkers.scan(body).spoken }

    /// Word count exactly as the writers state it: tag names such as <num> are not words.
    public static func wordCount(of spokenText: String) -> Int {
        LexicalFidelity.words(in: PiMarkers.stripTags(spokenText)).count
    }

    // MARK: Layouts

    private static let metadataMarker = "\n\n" + AuthoredPrompt.metadataHeading + "\n\n"
    private static let typedHeading = "\n\n## Typed\n\n"
    private static let rule = "\n\n---"
    /*
    Generated appendices that follow the metadata block on the Dev channel, mirroring
    TinkeringSection.removing and TinkeringPrompts' cleanup: the first one found ends the receipt.
    */
    private static let generatedMarkers = ["## Tinkering", "## Thoughts from Tokens", "## Summary · AI-generated by "]
        .map { "\n\n---\n\n" + $0 }

    /// Splits a metadata remainder into the receipt lines and an optional generated appendix.
    private static func splittingGenerated(_ tail: Substring) -> (Substring, String?) {
        let first = generatedMarkers.compactMap { tail.range(of: $0) }.min { $0.lowerBound < $1.lowerBound }
        guard let first else { return (tail, nil) }
        let appendix = tail[first.lowerBound...].dropFirst("\n\n---\n\n".count)
        return (tail[..<first.lowerBound], String(appendix))
    }

    private static func parseCurrent(_ text: String) -> PiEnvelope? {
        /*
        Same backwards rule as AuthoredPrompt.appendingTyped: only the LAST metadata heading
        followed by nothing but "> " lines ends the body. With a typed section the writer puts
        "---" before "## Typed" instead of before "# Metadata".
        */
        let start = text.index(text.startIndex, offsetBy: 4)
        guard let block = text.range(of: metadataMarker, options: .backwards),
              block.lowerBound >= start else { return nil }
        let (receipt, generated) = splittingGenerated(text[block.upperBound...])
        guard let lines = blockquote(receipt) else { return nil }
        let pre = text[start..<block.lowerBound]
        let body: String, typed: String?
        if let split = pre.range(of: rule + typedHeading) {
            body = String(pre[..<split.lowerBound]); typed = String(pre[split.upperBound...])
        } else if pre.hasSuffix(rule) {
            body = String(pre.dropLast(rule.count)); typed = nil
        } else if let split = pre.range(of: typedHeading) {
            body = String(pre[..<split.lowerBound]); typed = String(pre[split.upperBound...])
        } else {
            return nil
        }
        var envelope = make(.current, title: nil, body: body, typed: typed, metadata: lines)
        envelope.generated = generated
        return envelope
    }

    private static func parseHeaderFirst(_ text: String) -> PiEnvelope? {
        let afterMarker = text.dropFirst(4)
        guard let titleEnd = afterMarker.firstIndex(of: "\n") else { return nil }
        let title = String(afterMarker[..<titleEnd])
        let rest = afterMarker[titleEnd...]
        guard rest.hasPrefix("\n\n> *") else { return nil }
        let metaStart = rest.index(rest.startIndex, offsetBy: 2)
        guard let metaEnd = rest[metaStart...].range(of: "\n\n"),
              let lines = blockquote(rest[metaStart..<metaEnd.lowerBound]),
              lines.allSatisfy({ $0.hasPrefix("> *") }) else { return nil }
        let (body, typed) = splitTyped(rest[metaEnd.upperBound...])
        return make(.legacyHeaderFirst, title: title, body: body, typed: typed, metadata: lines)
    }

    private static func parseTranscriptHeading(_ text: String) -> PiEnvelope? {
        let afterMarker = text.dropFirst(4)
        guard let titleEnd = afterMarker.firstIndex(of: "\n") else { return nil }
        let rest = afterMarker[titleEnd...]
        guard rest.hasPrefix(metadataMarker) else { return nil }
        let metaStart = rest.index(rest.startIndex, offsetBy: metadataMarker.count)
        guard let words = rest[metaStart...].range(of: "\n\n## Transcript\n\n"),
              let lines = blockquote(rest[metaStart..<words.lowerBound]) else { return nil }
        let (body, typed) = splitTyped(rest[words.upperBound...])
        return make(.legacyTranscriptHeading, title: String(afterMarker[..<titleEnd]),
                    body: body, typed: typed, metadata: lines)
    }

    /// The first whole-line "## Typed" heading after a blank line ends the body.
    private static func splitTyped(_ tail: Substring) -> (String, String?) {
        guard let split = tail.range(of: typedHeading) else { return (String(tail), nil) }
        var body = tail[..<split.lowerBound]
        if body.hasSuffix(rule) { body = body.dropLast(rule.count) }
        return (String(body), String(tail[split.upperBound...]))
    }

    /// Lines of a metadata block, or nil unless every line starts with "> ".
    private static func blockquote(_ block: Substring) -> [String]? {
        let lines = block.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
        guard !lines.isEmpty, lines.allSatisfy({ $0.hasPrefix("> ") }) else { return nil }
        return lines
    }

    private static func make(_ layout: PiLayout, title: String?, body: String, typed: String?,
                             metadata: [String]) -> PiEnvelope {
        let scan = PiMarkers.scan(body)
        let stats = parseStats(metadata[0])
        return PiEnvelope(layout: layout, title: title, body: body, spokenText: scan.spoken,
                          pauses: scan.pauses, stats: stats,
                          notes: stats == nil ? metadata : Array(metadata.dropFirst()), typed: typed,
                          unplacedPauseCount: scan.unplacedCount, unplacedPauseTotal: scan.unplacedTotal)
    }

    /// `> *12.3456s · 61 words · 297 wpm · 3x thinking (4.1234s)*`; thinking and π-id parts are optional.
    static func parseStats(_ line: String) -> PiStats? {
        let pattern = #"^> \*(\d+(?:\.\d+)?)s · (\d+) words? · (\d+) wpm(?: · (\d+)x thinking \((\d+(?:\.\d+)?)s\))?(?: · π-id ([0-9a-f]{8}))?\*$"#
        guard let regex = try? NSRegularExpression(pattern: pattern),
              let match = regex.firstMatch(in: line, range: NSRange(line.startIndex..., in: line)) else { return nil }
        func group(_ index: Int) -> String? {
            Range(match.range(at: index), in: line).map { String(line[$0]) }
        }
        guard let seconds = group(1).flatMap(Double.init), let words = group(2).flatMap(Int.init),
              let wpm = group(3).flatMap(Int.init) else { return nil }
        return PiStats(seconds: seconds, words: words, wpm: wpm,
                       pauseCount: group(4).flatMap(Int.init), pauseTotal: group(5).flatMap(Double.init), piID: group(6))
    }
}

/*
Pause notation every Tokens generation wrote. Protected spans (code, <num>, <char>, <TC>, <TN>)
are copied untouched, exactly like InlineTalkMarkdown.transformProse, so a literal marker
inside code is never read as a pause. Placed markers become PiPause; unplaced ones are dropped
from the words without a position.
*/
enum PiMarkers {
    static let protected = #"(?s)```.*?(?:```|\z)|~~~.*?(?:~~~|\z)|`[^`]*(?:`|\z)|<num>.*?(?:</num>|\z)|<char>.*?(?:</char>|\z)|<TC>.*?(?:</TC>|\z)|<TN>.*?(?:</TN>|\z)"#
    // Groups: 1 pause, 2 thinking-tag seconds, 3 its unplaced count, 4 TK placed, 5/6 TK unplaced count/total.
    static let inline = #" ?(?:\*\[pause (\d+\.\d{4})\]\*|<thinking duration="(\d+\.\d{4})s"(?: placement="unplaced" count="(\d+)")?/>|— \(TK-(?:(\d+\.\d{4})s|unplaced ×(\d+) · (\d+\.\d{4})s · measured silence, position not aligned to words)\) —) ?"#
    // Groups: 1 and 6 placed seconds; 2/3, 4/5 and 7/8 unplaced count/total.
    static let annotation = #"^(?:THINK \((?:(\d+\.\d{4})s|unplaced ×(\d+) · (\d+\.\d{4})s · measured silence, position not aligned to words)\)|THINK unplaced ×(\d+) \((\d+\.\d{4})s\) · measured silence, position not aligned to words|\*Thinking · (?:(\d+\.\d{2,3}) s|unplaced ×(\d+) · (\d+\.\d{3}) s · measured silence, position not aligned to words)\*)$"#

    struct Result { var spoken: String; var pauses: [PiPause]; var unplacedCount = 0; var unplacedTotal = 0.0 }

    /// Removes <num>, <char>, <TC> and <TN> tags (and their italic stars), keeping the inner literal.
    /// Writers count words from delivery text, which never carries these tag names.
    static func stripTags(_ text: String) -> String {
        text.replacingOccurrences(of: #"\*?</?(?:num|char|TC|TN)>\*?"#, with: "", options: .regularExpression)
    }

    static func scan(_ body: String) -> Result {
        guard let protectedRegex = try? NSRegularExpression(pattern: protected),
              let inlineRegex = try? NSRegularExpression(pattern: inline),
              let annotationRegex = try? NSRegularExpression(pattern: annotation) else {
            return Result(spoken: collapse(body), pauses: [])
        }
        var pieces: [Substring] = [], pauses: [PiPause] = [], wordCount = 0
        var unplacedCount = 0, unplacedTotal = 0.0
        func unplaced(_ match: NSTextCheckingResult, _ count: Int, _ total: Int, in text: String) {
            guard let number = double(match, count, in: text), let seconds = double(match, total, in: text) else { return }
            unplacedCount += Int(number); unplacedTotal += seconds
        }
        func emit(_ piece: Substring) {
            pieces.append(piece)
            wordCount += LexicalFidelity.words(in: String(piece)).count
        }
        func double(_ match: NSTextCheckingResult, _ index: Int, in text: String) -> Double? {
            Range(match.range(at: index), in: text).flatMap { Double(text[$0]) }
        }
        func prose(_ segment: Substring) {
            for (lineIndex, lineSub) in segment.split(separator: "\n", omittingEmptySubsequences: false).enumerated() {
                if lineIndex > 0 { pieces.append("\n") }
                let line = String(lineSub)
                let whole = NSRange(line.startIndex..., in: line)
                if let match = annotationRegex.firstMatch(in: line, range: whole) {
                    if let seconds = double(match, 1, in: line) ?? double(match, 6, in: line) {
                        pauses.append(PiPause(seconds: seconds, wordIndex: wordCount))
                    }
                    unplaced(match, 2, 3, in: line); unplaced(match, 4, 5, in: line); unplaced(match, 7, 8, in: line)
                    continue
                }
                var cursor = line.startIndex
                for match in inlineRegex.matches(in: line, range: whole) {
                    guard let range = Range(match.range, in: line) else { continue }
                    emit(line[cursor..<range.lowerBound]); pieces.append(" ")
                    let placed = match.range(at: 3).location == NSNotFound
                    if let seconds = double(match, 1, in: line) ?? (placed ? double(match, 2, in: line) : nil)
                        ?? double(match, 4, in: line) {
                        pauses.append(PiPause(seconds: seconds, wordIndex: wordCount))
                    }
                    unplaced(match, 3, 2, in: line); unplaced(match, 5, 6, in: line)
                    cursor = range.upperBound
                }
                emit(line[cursor...])
            }
        }
        var cursor = body.startIndex
        for match in protectedRegex.matches(in: body, range: NSRange(body.startIndex..., in: body)) {
            guard let range = Range(match.range, in: body) else { continue }
            prose(body[cursor..<range.lowerBound]); emit(body[range])
            cursor = range.upperBound
        }
        prose(body[cursor...])
        return Result(spoken: collapse(pieces.joined()), pauses: pauses,
                      unplacedCount: unplacedCount, unplacedTotal: unplacedTotal)
    }

    /// Every whitespace run becomes one space; ends are trimmed.
    static func collapse(_ text: String) -> String {
        text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
    }
}

