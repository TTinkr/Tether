#!/usr/bin/env python3
"""Write a benchmark run's numbers into Sources/TokensCore/Settings/SpeechBenchmarks.swift.

    python3 scripts/speech_bench/to_swift.py scripts/speech_bench/results/2026-10-16-m5/summary.json \
        --machine-name "MacBook Pro" --build 81

Only the block between the GENERATED markers is replaced. Every number comes from summary.json
(which verify.py rebuilds from the raw receipts); nothing here is typed by hand. A model the run
measured but that failed gets no entry, so the app shows "—" for it.

Refuses a run the app must not ship:
- a dry run, a --models filter or a --clips limit (summary.json > selection, and the run's own
  env.json args), or any other partial selection;
- models that are not exactly the catalogue in models.json, or clips that are not the whole
  preregistered manifest.json (same sha256, every clip, every set);
- a results folder without its checked-in raw-receipts.tar.gz matching receipts.sha256.

The date is the run's start in America/Los_Angeles (the team's zone), whatever the runner's TZ.
The run id is written into SpeechBenchmarkRun.runID; the receipt test loads exactly that summary.
"""
import argparse
import hashlib
import json
import pathlib
import re
import sys
from datetime import datetime, timezone
from zoneinfo import ZoneInfo

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TARGET = ROOT / "Sources/TokensCore/Settings/SpeechBenchmarks.swift"
BEGIN = "    // BEGIN GENERATED by scripts/speech_bench/to_swift.py: do not edit by hand."
END = "    // END GENERATED"
TEAM_ZONE = ZoneInfo("America/Los_Angeles")

sys.path.insert(0, str(HERE))
import pack_receipts  # noqa: E402


def swift_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def refuse(why: str) -> None:
    sys.exit("refusing: " + why)


def check_complete(summary: dict, results: pathlib.Path) -> None:
    """Exit unless this is a full, receipt-backed run of every catalogue model on every clip."""
    if summary.get("schema") != "tinkr-speech-bench-summary/1" or summary.get("dry_run"):
        refuse("not a full tinkr-speech-bench-summary/1 run")

    catalogue = [m["id"] for m in json.loads((HERE / "models.json").read_text())["models"]]
    ids = [m["id"] for m in summary["models"]]
    if len(ids) != len(set(ids)) or set(ids) != set(catalogue):
        refuse("models %s are not the catalogue set %s" % (sorted(ids), sorted(catalogue)))

    selection = summary.get("selection")
    if selection is not None and (selection.get("models_requested") is not None or selection.get("clips_per_set_limit")
                                  or selection.get("dry_run") or selection.get("partial")):
        refuse("summary.json records a filter or partial selection: %s" % json.dumps(selection))

    manifest_bytes = (HERE / "manifest.json").read_bytes()
    if hashlib.sha256(manifest_bytes).hexdigest() != summary.get("manifest_sha256"):
        refuse("summary.json was made from a different manifest.json")
    clips = json.loads(manifest_bytes)["clips"]
    per_set = {s: sum(1 for c in clips if c["set"] == s) for s in ("test-clean", "test-other")}
    if summary["clips"]["total"] != len(clips) or summary["clips"]["per_set"] != per_set:
        refuse("clips %s are not the whole manifest (%d: %s)" % (summary["clips"], len(clips), per_set))
    for m in summary["models"]:
        if m.get("status") == "ok" and m["wer"]["combined"]["clips"] != len(clips):
            refuse("%s scored %s clips, not %d" % (m["id"], m["wer"]["combined"]["clips"], len(clips)))

    try:
        receipts = pack_receipts.load(str(results))
    except (OSError, ValueError) as e:
        refuse("raw receipts are not checked in (run pack_receipts.py): %s" % e)
    env = next((data for rel, data in receipts.items() if rel.endswith("/env.json")), None)
    if env is None:
        refuse("the run's env.json is not among its receipts")
    args = json.loads(env)["args"]
    if args.get("models") or args.get("clips") or args.get("dry_run"):
        refuse("the run was started with a filter: --models %r --clips %r --dry-run %r"
               % (args.get("models"), args.get("clips"), args.get("dry_run")))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("summary", type=pathlib.Path)
    parser.add_argument("--machine-name", required=True, help='e.g. "MacBook Pro" (the run records only Mac17,2)')
    parser.add_argument("--build", required=True, help="the app build whose speech workers ran, e.g. 81")
    args = parser.parse_args()

    summary = json.loads(args.summary.read_text())
    results = args.summary.resolve().parent
    check_complete(summary, results)

    env = summary["environment"]
    chip = env["chip"].replace("Apple ", "")
    memory = round(env["memory_bytes"] / 2**30)
    started = datetime.strptime(summary["started_utc"], "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    date = started.astimezone(TEAM_ZONE).strftime("%Y-%m-%d")
    sets = summary["clips"]["per_set"]
    clip_set = (f"{summary['clips']['total']} LibriSpeech recordings "
                f"({sets.get('test-clean', 0)} clear, {sets.get('test-other', 0)} harder)")

    rows = []
    for model in summary["models"]:
        if model.get("status") != "ok":
            continue
        wer = model["wer"]["combined"]
        talk = model["talk_10s_latency_s"]["median"]
        load = model.get("cold_first_result_s", {}).get("median")
        rows.append(
            f"        {swift_string(model['id'])}: MeasuredSpeechStats(wer: {wer['wer_percent']:.3f}, "
            f"talkSeconds: {talk:.4f}, loadSeconds: {('%.3f' % load) if load is not None else 'nil'}, clips: {wer['clips']}),"
        )
    if not rows:
        sys.exit("refusing: no measured model in the summary")

    folder = results.relative_to(ROOT) if ROOT in results.parents else results
    block = "\n".join([
        BEGIN,
        f"    // Run {summary['run_id']}, manifest {summary['manifest_sha256'][:12]}…, {folder}.",
        "    public static let run: SpeechBenchmarkRun? = SpeechBenchmarkRun(",
        f"        machine: {swift_string(f'{args.machine_name} ({chip}, {memory} GB)')}, date: {swift_string(date)},",
        f"        clipSet: {swift_string(clip_set)}, build: {swift_string(args.build)},",
        f"        runID: {swift_string(summary['run_id'])})",
        "",
        "    /// By catalogue id. A model without an entry was not measured.",
        "    public static let results: [String: MeasuredSpeechStats] = [",
        *rows,
        "    ]",
        END,
    ])
    source = TARGET.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(source):
        sys.exit(f"refusing: markers not found in {TARGET}")
    TARGET.write_text(pattern.sub(lambda _: block, source))
    print(f"wrote {len(rows)} models into {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
